// SKILL.md validation: rules 9-14
//
// Name and description mirror pi's loader contract. The metadata checks mirror
// scripts/skill-metadata.mjs's `validateSkillModelTierPlacement` and
// `validateSkillMetadata` exactly, including their exact error strings and
// control flow (a non-map `metadata` short-circuits before the per-key and
// tier checks, matching upstream). They are re-implemented rather than
// imported because this validator must remain zero-dependency.
// ---------------------------------------------------------------------------

function validateModelTierPlacement(frontmatter, ctx) {
  if (!Object.hasOwn(frontmatter, KAY_MODEL_TIER_METADATA_KEY)) return [];
  return [
    `${ctx}: frontmatter '${KAY_MODEL_TIER_METADATA_KEY}' must be nested under 'metadata'`,
  ];
}

function validateMetadataMap(metadata, ctx) {
  if (metadata === undefined) return [];
  if (
    typeof metadata !== "object" ||
    metadata === null ||
    Array.isArray(metadata)
  ) {
    return [`${ctx}: frontmatter 'metadata' must be a string-to-string map`];
  }

  const errors = [];
  for (const [key, value] of Object.entries(metadata)) {
    if (typeof value !== "string") {
      errors.push(`${ctx}: frontmatter metadata '${key}' must be a string`);
    }
  }

  const modelTier = metadata[KAY_MODEL_TIER_METADATA_KEY];
  if (typeof modelTier === "string" && !KAY_MODEL_TIERS.includes(modelTier)) {
    errors.push(
      `${ctx}: frontmatter metadata '${KAY_MODEL_TIER_METADATA_KEY}' must be one of ${KAY_MODEL_TIERS.join(", ")}`,
    );
  }
  return errors;
}

/**
 * The display bounds above, applied to the one author-controlled map that
 * reaches the index verbatim. Kept apart from `validateMetadataMap`, which
 * mirrors Bonsai's own authoring gates string for string: these caps are this
 * format's own, and mixing them into that mirror would make it a mirror of
 * nothing.
 */
function validateMetadataBounds(metadata, ctx) {
  if (
    metadata === undefined ||
    typeof metadata !== "object" ||
    metadata === null ||
    Array.isArray(metadata)
  ) {
    return [];
  }

  const errors = [];
  const entries = Object.entries(metadata);
  if (entries.length > MAX_METADATA_ENTRIES) {
    errors.push(
      `${ctx}: frontmatter 'metadata' has ${entries.length} entries; the limit is ${MAX_METADATA_ENTRIES}`,
    );
  }

  for (const [key, value] of entries) {
    if (key.length > MAX_METADATA_KEY_LENGTH) {
      // Truncated in the message: the offending key is by definition too long
      // to print, and a wall of it would bury every other error.
      errors.push(
        `${ctx}: frontmatter metadata key '${key.slice(0, 32)}...' exceeds ${MAX_METADATA_KEY_LENGTH} characters (${key.length})`,
      );
    }
    if (typeof value !== "string") continue;
    // One cap per field, never two: `version` is bounded tighter than the rest,
    // and applying both would report a long version twice.
    const limit =
      key === "version"
        ? MAX_METADATA_VERSION_LENGTH
        : MAX_METADATA_VALUE_LENGTH;
    if (value.length > limit) {
      errors.push(
        `${ctx}: frontmatter metadata '${key}' exceeds ${limit} characters (${value.length})`,
      );
    }
  }
  return errors;
}

function validateName(frontmatter, expectedName, ctx) {
  if (
    typeof frontmatter.name !== "string" ||
    frontmatter.name.trim().length === 0
  ) {
    return [
      `${ctx}: frontmatter 'name' is required and must be a non-empty string`,
    ];
  }
  if (frontmatter.name !== expectedName) {
    return [
      `${ctx}: frontmatter name '${frontmatter.name}' must match the skill directory '${expectedName}'`,
    ];
  }
  return [];
}

function validateDescription(frontmatter, ctx) {
  if (
    typeof frontmatter.description !== "string" ||
    frontmatter.description.trim().length === 0
  ) {
    return [
      `${ctx}: frontmatter 'description' is required and must be a non-empty string`,
    ];
  }
  if (frontmatter.description.length > MAX_SKILL_DESCRIPTION_LENGTH) {
    return [
      `${ctx}: frontmatter 'description' exceeds ${MAX_SKILL_DESCRIPTION_LENGTH} characters (${frontmatter.description.length})`,
    ];
  }
  return [];
}

/** Read and validate every declared skill's SKILL.md. Skips a path rule 7 already flagged. */
function readAndValidateSkills(root, manifest) {
  const errors = [];
  const skills = [];

  for (const entry of manifest.skills) {
    const dirAbs = resolveSkillDir(root, entry.path);
    // Same predicate rule 7 uses, so a path it already rejected (missing, or a
    // symlink) is reported once rather than again per SKILL.md problem behind
    // it.
    if (!isRealDirectory(dirAbs)) continue;

    const ctx = `${entry.path}/SKILL.md`;
    const skillMdAbs = join(dirAbs, "SKILL.md");
    if (!existsSync(skillMdAbs)) {
      errors.push(`${ctx} is missing`);
      continue;
    }

    const raw = readFileSync(skillMdAbs, "utf8");
    const frontmatterResult = parseFrontmatterBlock(raw, ctx);
    if (frontmatterResult.error) {
      errors.push(frontmatterResult.error);
      continue;
    }
    const frontmatter = frontmatterResult.value;

    const skillErrors = [
      ...validateName(frontmatter, entry.path, ctx),
      ...validateDescription(frontmatter, ctx),
      ...validateModelTierPlacement(frontmatter, ctx),
      ...validateMetadataMap(frontmatter.metadata, ctx),
      ...validateMetadataBounds(frontmatter.metadata, ctx),
    ];
    if (skillErrors.length > 0) {
      errors.push(...skillErrors);
      continue;
    }

    skills.push({ entry, frontmatter });
  }

  return { errors, skills };
}

// ---------------------------------------------------------------------------
// Git derivation: commit / creator / contributors, and the version-bump warning
// ---------------------------------------------------------------------------

/** Run git read-only against `root`; null on any failure (not a repo, no commits, no git). */
function gitCapture(root, args) {
  const result = spawnSync("git", args, { cwd: root, encoding: "utf8" });
  return result.status === 0 ? result.stdout : null;
}

/**
 * `commit` is the newest commit touching `relPath`; `creator` is the author of
 * the oldest; `contributors` lists distinct authors oldest-first. All three
 * degrade to empty (never throw) outside a git checkout, with zero commits, or
 * for an untracked new skill directory.
 */
function deriveGitFields(root, relPath) {
  const empty = { commit: "", creator: "", contributors: [] };
  // Plain form, not --follow: --follow is documented for a single file, its
  // rename-following is meaningless for a directory, and plain history is what
  // this needs.
  const output = gitCapture(root, ["log", "--format=%H%x09%an", "--", relPath]);
  if (output === null) return empty;

  const rows = output
    .split("\n")
    .filter((line) => line.length > 0)
    .map((line) => {
      const tab = line.indexOf("\t");
      return tab === -1
        ? { sha: line, author: "" }
        : { sha: line.slice(0, tab), author: line.slice(tab + 1) };
    });
  if (rows.length === 0) return empty;

  const contributors = [];
  for (let index = rows.length - 1; index >= 0; index -= 1) {
    if (!contributors.includes(rows[index].author))
      contributors.push(rows[index].author);
  }
  return {
    commit: rows[0].sha,
    creator: rows[rows.length - 1].author,
    contributors,
  };
}

/**
 * The most recent commit that changed how many times the literal string
 * `version` appears in `relSkillMdPath`, i.e. the commit that last set it to
 * its current value. `git log -S<string>` (pickaxe) is a literal substring
 * search, not a regex, so this is safe for an arbitrary version string.
 */
function findVersionBumpCommit(root, relSkillMdPath, version) {
  const output = gitCapture(root, [
    "log",
    `-S${version}`,
    "--format=%H",
    "--",
    relSkillMdPath,
  ]);
  if (output === null) return null;
  const lines = output.split("\n").filter((line) => line.length > 0);
  return lines.length > 0 ? lines[0] : null;
}

// ---------------------------------------------------------------------------
// Index building (including the version-bump warning) and freshness
// ---------------------------------------------------------------------------

/**
 * The plugin rows of the index, sorted by path so the file is canonical.
 *
 * `commit`, `creator`, and `contributors` are derived exactly as they are for
 * a skill — from git history over the plugin's own directory — and degrade to
 * empty the same way. `digest` is derived from the plugin directory's own
 * content instead (see "Artifact digest" above), never from git, and is
 * always present: `computeArtifactDigests` already excluded any plugin whose
 * tree contains a symlink before this ever runs. `metadata` is always `{}`
 * today: a `kay-plugin.json` carries no string-to-string map of its own, and
 * inventing one from other manifest fields would publish a claim the format
 * never promised. The key is present regardless so a consumer has one shape
 * to handle, matching the skill rows' own rule.
 */
function buildPluginRows(root, plugins, pluginDigests) {
  const sorted = [...plugins].sort((a, b) =>
    a.entry.path < b.entry.path ? -1 : a.entry.path > b.entry.path ? 1 : 0,
  );
  return sorted.map(({ entry, manifest }) => {
    const git = deriveGitFields(root, pluginDisplayPath(entry.path));
    return {
      path: entry.path,
      id: manifest.id,
      displayName: manifest.displayName,
      description: manifest.description,
      category: entry.category,
      version: manifest.version,
      sdk: manifest.sdk,
      targets: manifest.targets,
      commit: git.commit,
      creator: git.creator,
      contributors: git.contributors,
      metadata: {},
      digest: pluginDigests.get(entry.path),
    };
  });
}

function buildIndex(
  root,
  manifest,
  skills,
  plugins,
  skillDigests,
  pluginDigests,
) {
  const warnings = [];
  const sorted = [...skills].sort((a, b) =>
    a.entry.path < b.entry.path ? -1 : a.entry.path > b.entry.path ? 1 : 0,
  );

  const skillRows = sorted.map(({ entry, frontmatter }) => {
    const git = deriveGitFields(root, entry.path);
    const metadata = frontmatter.metadata;
    const version =
      typeof metadata?.version === "string" ? metadata.version : "";

    // Version drift is a warning, never an error. Forgetting to bump a version is a
    // documentation sin, not a correctness one. Skipped with no basis for
    // comparison: no declared version, or no commit history yet.
    if (version !== "" && git.commit !== "") {
      const bumpCommit = findVersionBumpCommit(
        root,
        `${entry.path}/SKILL.md`,
        version,
      );
      if (bumpCommit !== null && bumpCommit !== git.commit) {
        warnings.push(
          `${entry.path}: content changed since metadata.version "${version}" was last bumped ` +
            `(bump ${bumpCommit.slice(0, 12)}, latest change ${git.commit.slice(0, 12)}); ` +
            "consider bumping metadata.version.",
        );
      }
    }

    return {
      path: entry.path,
      name: entry.path,
      description: frontmatter.description,
      category: entry.category,
      version,
      commit: git.commit,
      creator: git.creator,
      contributors: git.contributors,
      // Always present, even when the skill declares no metadata: block, so
      // an index consumer has exactly one shape to handle instead of two
      // conventions for "absent" (a missing key vs. an empty object).
      metadata: metadata ?? {},
      // Derived from the skill directory's own content (see "Artifact
      // digest" above), never from git. Always present: `computeArtifactDigests`
      // already excluded any skill whose tree contains a symlink before this
      // ever runs.
      digest: skillDigests.get(entry.path),
    };
  });

  const index = {
    schemaVersion: 1,
    name: manifest.name,
    ...(typeof manifest.description === "string" &&
    manifest.description.length > 0
      ? { description: manifest.description }
      : {}),
    generatedAt: new Date().toISOString(),
    categories: manifest.categories.map((category) => ({
      id: category.id,
      label: category.label,
      ...(typeof category.description === "string" &&
      category.description.length > 0
        ? { description: category.description }
        : {}),
    })),
    skills: skillRows,
    // Always present, even for a marketplace that carries no plugins, for the
    // same reason each skill's `metadata` is: one shape for a consumer to
    // handle rather than two conventions for "none". A skills-only
    // marketplace upgrading to this validator therefore reads as stale once,
    // and one `--fix` settles it.
    plugins: buildPluginRows(root, plugins, pluginDigests),
  };

  return { index, warnings };
}

function serializeIndex(index) {
  return `${JSON.stringify(index, null, 2)}\n`;
}

/**
 * Rule 15 (owner ruling 1A, 2026-08-26): the staleness comparison below
 * ignores every field a committed index cannot honestly reproduce, so that
 * only fields derived from marketplace.json and the skill directories, not
 * from git history or the clock, decide whether the index is stale.
 *
 * Excluded:
 *   - `generatedAt`, a timestamp, excluded since the very first version of
 *     this check.
 *   - Each skill's and each plugin's `commit`, `creator`, and
 *     `contributors`. These are
 *     derived from git history over the skill's directory INCLUDING the
 *     newest commit that touches it, so a commit that adds or edits a skill
 *     and regenerates the index in that same commit can never make the
 *     result agree with a fresh rebuild: the index cannot record the commit
 *     that contains it. Gating on them turned an ordinary one-commit
 *     contribution, and any squash-merge (which collapses a multi-author
 *     history into one commit and so changes `creator` and `contributors`
 *     with no content change at all), into a guaranteed-stale CI failure.
 *
 * Still compared exactly: the marketplace's own `name`, `description`, and
 * `categories`, and each skill's `path`, `name`, `description`, `category`,
 * `version`, `metadata`, and `digest`. All of those come from
 * marketplace.json and the skill directories as they stand in the tree being
 * checked, which a commit CAN already fully describe about itself. `digest`
 * belongs in this list, not the excluded one, even though it is computed
 * fresh every run exactly like `commit` is: unlike `commit`, it is derived
 * purely from file content, never from git history, so a commit that adds or
 * edits a skill or a plugin and regenerates the index together CAN already
 * describe its own digest — there is no "cannot record itself" problem for a
 * value git history never entered into. A stale digest is exactly as real a
 * drift as a stale description, and rule 15 must catch it the same way.
 *
 * `commit`, `creator`, and `contributors` are still computed by
 * `deriveGitFields` and still written into the index by `--fix`: only this
 * comparison ignores them. A marketplace repo's README documents the
 * consequence for a human: those three fields can lag by a contribution
 * until someone next runs `--fix`, by design, since CI only asserts what git
 * can keep true about a commit that has not happened yet.
 */
function projectStalenessFields(index) {
  if (typeof index !== "object" || index === null) return index;
  const projected = { ...index };
  delete projected.generatedAt;
  // Both row arrays are projected identically, and for one reason: a plugin's
  // `commit`, `creator`, and `contributors` come from the same
  // `deriveGitFields` read over its own directory, so a commit that adds a
  // plugin and regenerates the index together can no more describe its own
  // hash than a skill's can. Every remaining plugin field —
  // `path,id,displayName,description,category,version,sdk,targets,metadata` —
  // comes from marketplace.json and the plugin's kay-plugin.json as they
  // stand in the tree being checked, so all of it is compared exactly.
  for (const key of ["skills", "plugins"]) {
    if (!Array.isArray(projected[key])) continue;
    projected[key] = projected[key].map((row) => {
      if (typeof row !== "object" || row === null) return row;
      const fileDerived = { ...row };
      delete fileDerived.commit;
      delete fileDerived.creator;
      delete fileDerived.contributors;
      return fileDerived;
    });
  }
  return projected;
}

/** Rule 15: the committed index is stale if it is missing, unparsable, or its file-derived fields (see `projectStalenessFields`) differ from a fresh build. */
function checkIndexFreshness(indexPath, freshIndex) {
  if (!existsSync(indexPath)) {
    return {
      fresh: false,
      reason: "marketplace.index.json does not exist yet",
    };
  }
  let onDisk;
  try {
    onDisk = JSON.parse(readFileSync(indexPath, "utf8"));
  } catch (error) {
    return {
      fresh: false,
      reason: `marketplace.index.json is not valid JSON (${error.message})`,
    };
  }
  if (
    JSON.stringify(projectStalenessFields(onDisk)) !==
    JSON.stringify(projectStalenessFields(freshIndex))
  ) {
    return {
      fresh: false,
      reason: "it does not match marketplace.json and the skill directories",
    };
  }
  return { fresh: true };
}

// ---------------------------------------------------------------------------
// Orchestration
// ---------------------------------------------------------------------------

function validateMarketplace(root) {
  const manifestOutcome = readManifest(root);
  if (manifestOutcome.errors.length > 0) {
    return { errors: manifestOutcome.errors, warnings: [], index: null };
  }
  const manifest = manifestOutcome.manifest;

  const structuralErrors = [
    ...checkDeclaredSkillDirsExist(root, manifest),
    ...checkForUndeclaredSkillDirs(root, manifest),
    ...checkDeclaredPluginDirsExist(root, manifest),
    ...checkForUndeclaredPluginDirs(root, manifest),
  ];
  const { errors: skillErrors, skills } = readAndValidateSkills(root, manifest);
  const { errors: pluginErrors, plugins } = readAndValidatePlugins(
    root,
    manifest,
  );
  const {
    errors: digestErrors,
    skillDigests,
    pluginDigests,
  } = computeArtifactDigests(root, skills, plugins);
  const errors = [
    ...structuralErrors,
    ...skillErrors,
    ...pluginErrors,
    ...digestErrors,
  ];
  if (errors.length > 0) {
    return { errors, warnings: [], index: null };
  }

  const { index, warnings } = buildIndex(
    root,
    manifest,
    skills,
    plugins,
    skillDigests,
    pluginDigests,
  );
  return { errors: [], warnings, index };
}

function main() {
  const { fix, root } = parseArgs(process.argv.slice(2));

  if (!isDirectory(root)) {
    console.error(`\u2717 --root '${root}' is not a directory`);
    process.exitCode = 1;
    return;
  }

  const { errors, warnings, index } = validateMarketplace(root);

  for (const warning of warnings) console.warn(`\u26a0 ${warning}`);

  if (errors.length > 0) {
    for (const error of errors) console.error(`\u2717 ${error}`);
    console.error(`\u2717 ${errors.length} problem(s) found.`);
    process.exitCode = 1;
    return;
  }

  const categoryWord =
    index.categories.length === 1 ? "category" : "categories";
  const contents = `${index.skills.length} skill(s), ${index.plugins.length} plugin(s), ${index.categories.length} ${categoryWord}`;
  const indexPath = join(root, "marketplace.index.json");

  if (fix) {
    writeFileSync(indexPath, serializeIndex(index), "utf8");
    console.log(`\u2713 wrote marketplace.index.json (${contents})`);
    process.exitCode = 0;
    return;
  }

  const freshness = checkIndexFreshness(indexPath, index);
  if (!freshness.fresh) {
    console.error(
      `\u2717 marketplace.index.json is stale: ${freshness.reason}.`,
    );
    console.error(
      "\u2717 Run 'node tools/validate.mjs --fix' to regenerate it.",
    );
    console.error("\u2717 1 problem(s) found.");
    process.exitCode = 1;
    return;
  }

  console.log(`\u2713 marketplace.json is valid (${contents})`);
  console.log("\u2713 marketplace.index.json is up to date");
  process.exitCode = 0;
}

try {
  main();
} catch (error) {
  console.error(
    `\u2717 validate.mjs crashed: ${error instanceof Error ? error.message : String(error)}`,
  );
  process.exitCode = 1;
}
