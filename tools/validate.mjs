// Validate a skill-marketplace repository, and (re)generate its committed
// marketplace.index.json.
//
// This script ships into a marketplace repository as tools/validate.mjs and runs
// there, in that repository's own CI. There is no package.json and no
// node_modules to rely on: every import below is a Node builtin, and this file
// must never grow a dependency.
//
// Usage:
//   node tools/validate.mjs             validate; also fail if the committed
//                                        marketplace.index.json is stale
//   node tools/validate.mjs --fix       validate, then (re)write
//                                        marketplace.index.json
//   node tools/validate.mjs --root DIR  run against DIR instead of the current
//                                        directory
//
// A marketplace repository holds, at the root this script is pointed at:
//   marketplace.json         hand-maintained: name, categories, skill and
//                             plugin paths
//   marketplace.index.json   generated by this script; never hand-edit it
//   <skill directories>      each an ordinary SKILL.md folder
//   plugins/<plugin dirs>    each an ordinary kay-plugin.json folder
//
// Skills sit at the root and plugins sit one level down under `plugins/`. That
// asymmetry is deliberate and load-bearing, not an inconsistency: Bonsai resolves
// a marketplace's SKILLS from the root it syncs, where "any directory with a
// SKILL.md" is the structural rule, while it resolves that marketplace's
// PLUGINS through a separate plugin repository source pointed at `subdir:
// "plugins"`, where "any directory with a kay-plugin.json" is the structural
// rule. Putting plugins under their own directory lets one repository serve
// both channels without either scan seeing the other's directories.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  lstatSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";

// Mirrors the skill-loader and model-tier limits this zero-dependency copy
// cannot import from Bonsai. Keep these literals aligned with pi's skill loader
// and packages/product-catalog/src/model-tier-catalog.ts.
const MAX_SKILL_NAME_LENGTH = 64;
const MAX_SKILL_DESCRIPTION_LENGTH = 1024;
const SKILL_NAME_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u;
const KAY_MODEL_TIERS = ["small", "medium", "large", "ultra"];
const KAY_MODEL_TIER_METADATA_KEY = "kay-model-tier";

// Display bounds, not loader limits. Bonsai's Marketplace pane reads this index
// over a wire schema that caps every field below, and drops or truncates what
// exceeds a cap. An index can therefore be perfectly valid by this format and
// still degrade on arrival, which a marketplace author would never learn from
// their own CI. Catching it here is the whole point: an author can fix a long
// label before publishing, and cannot fix a silent truncation afterwards.
//
// Only author-controllable fields are bounded. Each skill's git-derived
// `commit`, `creator`, and `contributors` are deliberately exempt: nobody can
// shorten a contributor list, so gating CI on one would be a check with no
// available fix. Bonsai's display side handles those.
const MAX_MARKETPLACE_NAME_LENGTH = 4096;
const MAX_MARKETPLACE_DESCRIPTION_LENGTH = 4096;
const MAX_CATEGORIES = 64;
const MAX_CATEGORY_ID_LENGTH = 512;
const MAX_CATEGORY_LABEL_LENGTH = 4096;
const MAX_CATEGORY_DESCRIPTION_LENGTH = 4096;
const MAX_METADATA_ENTRIES = 64;
const MAX_METADATA_KEY_LENGTH = 256;
const MAX_METADATA_VALUE_LENGTH = 4096;
const MAX_METADATA_VERSION_LENGTH = 512;

// ---------------------------------------------------------------------------
// Plugins
//
// A marketplace may also carry plugins, each an ordinary Bonsai plugin directory
// under `plugins/` with a `kay-plugin.json` at its top level.
//
// What this script checks about a plugin, and what it deliberately does not:
// it validates the plugin's IDENTITY — the four fields the index publishes as
// its own claim about the plugin (`id`, `version`, `displayName`,
// `description`) — plus the display bounds those fields must respect. It is
// not a second implementation of Bonsai's plugin manifest schema. Bonsai's own
// parser is the authority on everything else in that file (entrypoints,
// contributions, permissions), and re-deriving those rules here would produce
// a mirror that drifts from the real one without ever being the thing that
// decides.
//
// `compatibility.sdk` is checked as a bounded non-empty string and nothing
// more. The npm range grammar Bonsai matches it against lives in a 194-line
// matcher whose whole design point is to REFUSE a range it cannot parse; a
// zero-dependency re-implementation here would be a second grammar that
// disagrees with the first one silently. An unparseable range is therefore
// caught at install time, where Bonsai reports it on the plugin's row, not here.
const PLUGINS_DIR_NAME = "plugins";
const PLUGIN_MANIFEST_FILENAME = "kay-plugin.json";
// Mirrors `PluginId` in @bonsai/plugin-protocol's common.ts: dot-separated
// lowercase segments, each starting with a letter. Hyphens are admitted
// inside a segment.
const PLUGIN_ID_RE = /^[a-z][a-z0-9-]*(?:\.[a-z][a-z0-9-]*)*$/u;
// Mirrors `SEMVER_PATTERN` in @bonsai/plugin-protocol's semver.ts, which is what
// Bonsai holds a plugin's own `version` field to.
const SEMVER_RE =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$/u;
const MAX_PLUGIN_ID_LENGTH = 512;
const MAX_PLUGIN_TEXT_LENGTH = 4096;
const MAX_PLUGIN_VERSION_LENGTH = 512;
const MAX_PLUGIN_SDK_RANGE_LENGTH = 512;
const MAX_PLUGIN_TARGETS = 16;
const MAX_PLUGIN_TARGET_NAME_LENGTH = 256;

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function parseArgs(argv) {
  const fix = argv.includes("--fix");
  const rootIndex = argv.indexOf("--root");
  if (rootIndex === -1) return { fix, root: process.cwd() };

  const value = argv[rootIndex + 1];
  if (!value || value.startsWith("--")) {
    console.error("\u2717 --root requires a directory argument");
    process.exit(1);
  }
  return { fix, root: resolve(value) };
}

// ---------------------------------------------------------------------------
// Path helpers
//
// A marketplace skill path is one direct child directory name, not a nested
// relative path. Enforcing the loader's skill-name grammar here makes the
// root-only layout explicit and prevents both POSIX '/' and Windows '\\'
// separators from ever reaching filesystem resolution.
// ---------------------------------------------------------------------------

function resolveSkillDir(root, relPath) {
  return join(root, relPath);
}

/**
 * A plugin path is one direct child directory name of `plugins/`, under the
 * same grammar a skill path uses. Same reasoning as `resolveSkillDir`: the
 * grammar is enforced before this ever reaches filesystem resolution, so
 * neither a POSIX '/' nor a Windows '\\' separator can escape the directory.
 */
function resolvePluginDir(root, relPath) {
  return join(root, PLUGINS_DIR_NAME, relPath);
}

/** The path a message names a plugin by, always `plugins/<dir>`. */
function pluginDisplayPath(relPath) {
  return `${PLUGINS_DIR_NAME}/${relPath}`;
}

function isSkillDirectoryName(value) {
  return value.length <= MAX_SKILL_NAME_LENGTH && SKILL_NAME_RE.test(value);
}

function isDirectory(absPath) {
  return existsSync(absPath) && statSync(absPath).isDirectory();
}

/**
 * `lstat`, never `stat`: every question below is about the entry itself, not
 * about whatever it points at. A skill directory must be a real directory at
 * the marketplace root, so a symlink standing where one belongs is a
 * different thing that has to be recognized as such, not followed.
 */
function lstatOrNull(absPath) {
  try {
    return lstatSync(absPath);
  } catch {
    return null;
  }
}

function isSymlink(absPath) {
  return lstatOrNull(absPath)?.isSymbolicLink() === true;
}

function isRealDirectory(absPath) {
  return lstatOrNull(absPath)?.isDirectory() === true;
}

// ---------------------------------------------------------------------------
// marketplace.json: rules 1-6 (skills) and 17-18 (plugins)
// ---------------------------------------------------------------------------

function readManifest(root) {
  const manifestPath = join(root, "marketplace.json");
  if (!existsSync(manifestPath)) {
    return {
      errors: [
        "marketplace.json is missing; expected it at the marketplace root",
      ],
    };
  }

  const raw = readFileSync(manifestPath, "utf8");
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    return { errors: [`marketplace.json is not valid JSON: ${error.message}`] };
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    return { errors: ["marketplace.json must be a JSON object"] };
  }

  const errors = [];

  if (parsed.schemaVersion !== 1) {
    errors.push("marketplace.json: 'schemaVersion' must be 1");
  }
  if (typeof parsed.name !== "string" || parsed.name.trim().length === 0) {
    errors.push("marketplace.json: 'name' must be a non-empty string");
  } else if (parsed.name.length > MAX_MARKETPLACE_NAME_LENGTH) {
    errors.push(
      `marketplace.json: 'name' exceeds ${MAX_MARKETPLACE_NAME_LENGTH} characters (${parsed.name.length})`,
    );
  }
  if (
    typeof parsed.description === "string" &&
    parsed.description.length > MAX_MARKETPLACE_DESCRIPTION_LENGTH
  ) {
    errors.push(
      `marketplace.json: 'description' exceeds ${MAX_MARKETPLACE_DESCRIPTION_LENGTH} characters (${parsed.description.length})`,
    );
  }

  const categoryIds = new Set();
  const categories = [];
  if (parsed.categories !== undefined) {
    if (!Array.isArray(parsed.categories)) {
      errors.push("marketplace.json: 'categories' must be an array");
    } else {
      if (parsed.categories.length > MAX_CATEGORIES) {
        errors.push(
          `marketplace.json: 'categories' has ${parsed.categories.length} entries; the limit is ${MAX_CATEGORIES}`,
        );
      }
      parsed.categories.forEach((category, index) => {
        if (
          typeof category !== "object" ||
          category === null ||
          Array.isArray(category)
        ) {
          errors.push(
            `marketplace.json: categories[${index}] must be an object`,
          );
          return;
        }
        if (
          typeof category.id !== "string" ||
          category.id.trim().length === 0
        ) {
          errors.push(
            `marketplace.json: categories[${index}] is missing a non-empty 'id'`,
          );
          return;
        }
        if (
          typeof category.label !== "string" ||
          category.label.trim().length === 0
        ) {
          errors.push(
            `marketplace.json: category '${category.id}' is missing a non-empty 'label'`,
          );
          return;
        }
        if (categoryIds.has(category.id)) {
          errors.push(
            `marketplace.json: duplicate category id '${category.id}'`,
          );
          return;
        }
        // The three length checks below report and carry on, rather than
        // returning like the checks above them. An over-long label is still a
        // usable category id, so registering it keeps every skill pointing at
        // it from collecting a second, misleading 'unknown category' error on
        // top of the one real problem. Nothing is written either way: any
        // error at all stops the run before the index is built.
        if (category.id.length > MAX_CATEGORY_ID_LENGTH) {
          errors.push(
            `marketplace.json: category id exceeds ${MAX_CATEGORY_ID_LENGTH} characters (${category.id.length})`,
          );
        }
        if (category.label.length > MAX_CATEGORY_LABEL_LENGTH) {
          errors.push(
            `marketplace.json: category '${category.id}' label exceeds ${MAX_CATEGORY_LABEL_LENGTH} characters (${category.label.length})`,
          );
        }
        if (
          typeof category.description === "string" &&
          category.description.length > MAX_CATEGORY_DESCRIPTION_LENGTH
        ) {
          errors.push(
            `marketplace.json: category '${category.id}' description exceeds ${MAX_CATEGORY_DESCRIPTION_LENGTH} characters (${category.description.length})`,
          );
        }
        categoryIds.add(category.id);
        categories.push(category);
      });
    }
  }

  const seenPaths = new Set();
  const skills = [];
  if (parsed.skills !== undefined) {
    if (!Array.isArray(parsed.skills)) {
      errors.push("marketplace.json: 'skills' must be an array");
    } else {
      parsed.skills.forEach((entry, index) => {
        if (
          typeof entry !== "object" ||
          entry === null ||
          Array.isArray(entry)
        ) {
          errors.push(`marketplace.json: skills[${index}] must be an object`);
          return;
        }
        if (typeof entry.path !== "string" || entry.path.trim().length === 0) {
          errors.push(
            `marketplace.json: skills[${index}] is missing a string 'path'`,
          );
          return;
        }
        if (!isSkillDirectoryName(entry.path)) {
          errors.push(
            `marketplace.json: skill path '${entry.path}' must name one direct child directory using lowercase letters, digits, and single hyphens`,
          );
          return;
        }
        if (seenPaths.has(entry.path)) {
          errors.push(`marketplace.json: duplicate skill path '${entry.path}'`);
          return;
        }
        seenPaths.add(entry.path);
        if (
          typeof entry.category !== "string" ||
          entry.category.trim().length === 0
        ) {
          errors.push(
            `marketplace.json: skill '${entry.path}' must declare a 'category'`,
          );
          return;
        }
        if (!categoryIds.has(entry.category)) {
          errors.push(
            `marketplace.json: skill '${entry.path}' references unknown category '${entry.category}'`,
          );
          return;
        }
        skills.push(entry);
      });
    }
  }

  // Rules 17-18. `plugins` follows `skills` field for field, including its
  // optionality: omitting it entirely and declaring an empty array are the
  // same statement. Its `path` grammar is the skill-name grammar, applied one
  // level down, so the two manifest arrays stay readable as one shape.
  const seenPluginPaths = new Set();
  const plugins = [];
  if (parsed.plugins !== undefined) {
    if (!Array.isArray(parsed.plugins)) {
      errors.push("marketplace.json: 'plugins' must be an array");
    } else {
      parsed.plugins.forEach((entry, index) => {
        if (
          typeof entry !== "object" ||
          entry === null ||
          Array.isArray(entry)
        ) {
          errors.push(`marketplace.json: plugins[${index}] must be an object`);
          return;
        }
        if (typeof entry.path !== "string" || entry.path.trim().length === 0) {
          errors.push(
            `marketplace.json: plugins[${index}] is missing a string 'path'`,
          );
          return;
        }
        if (!isSkillDirectoryName(entry.path)) {
          errors.push(
            `marketplace.json: plugin path '${entry.path}' must name one direct child directory of ${PLUGINS_DIR_NAME}/ using lowercase letters, digits, and single hyphens`,
          );
          return;
        }
        if (seenPluginPaths.has(entry.path)) {
          errors.push(
            `marketplace.json: duplicate plugin path '${entry.path}'`,
          );
          return;
        }
        seenPluginPaths.add(entry.path);
        if (
          typeof entry.category !== "string" ||
          entry.category.trim().length === 0
        ) {
          errors.push(
            `marketplace.json: plugin '${entry.path}' must declare a 'category'`,
          );
          return;
        }
        if (!categoryIds.has(entry.category)) {
          errors.push(
            `marketplace.json: plugin '${entry.path}' references unknown category '${entry.category}'`,
          );
          return;
        }
        plugins.push(entry);
      });
    }
  }

  return {
    errors,
    manifest: {
      name: parsed.name,
      description: parsed.description,
      categories,
      skills,
      plugins,
    },
  };
}

// ---------------------------------------------------------------------------
// Filesystem cross-checks: rules 7-8
// ---------------------------------------------------------------------------

/**
 * Rule 7: every manifest skill path must have a real directory on disk.
 *
 * A symlink is named as its own error rather than followed. `statSync` follows
 * links, so a symlinked skill path used to pass this rule while breaking the
 * format in two ways at once: a clone made with `core.symlinks=false` (Windows
 * without developer mode, and any repo configured that way) materializes the
 * link as a plain text file and the skill directory simply is not there, and a
 * link pointing outside the root lets CI bless bytes the marketplace does not
 * contain.
 */
function checkDeclaredSkillDirsExist(root, manifest) {
  const errors = [];
  for (const entry of manifest.skills) {
    const dirAbs = resolveSkillDir(root, entry.path);
    if (isSymlink(dirAbs)) {
      errors.push(
        `marketplace.json: skill '${entry.path}' is a symlink; a skill directory must be a real directory at the marketplace root`,
      );
      continue;
    }
    if (!isRealDirectory(dirAbs)) {
      errors.push(
        `marketplace.json: skill '${entry.path}' has no directory on disk`,
      );
    }
  }
  return errors;
}

/**
 * Rule 8 (owner ruling 2B, 2026-08-26): a skill directory is defined
 * structurally, not by which manifest entries happen to exist: any directory
 * directly under the marketplace root that contains a SKILL.md is a skill
 * directory, and every one of them needs a manifest entry. This scans the
 * root itself, so a marketplace declaring zero skills is still scanned; the
 * previous version scanned only the parent directories of already-declared
 * paths, so an empty `skills` array meant nothing was scanned at all, and a
 * freshly seeded repo could carry an undeclared skill directory and still
 * pass CI clean.
 *
 * A shallow, non-recursive read of the root is enough: skills sit exactly
 * one directory deep, the same invariant `resolveSkillDir` and the rest of
 * this format rely on. `node_modules` and any dot-directory (`.github`,
 * `.git`) are skipped by name, both for speed and because neither is ever a
 * skill directory in practice; everything else is judged purely by whether
 * it has a SKILL.md. A directory without one, `tools/` included, is simply
 * not a skill directory and is never scanned as one, regardless of its name.
 */
function checkForUndeclaredSkillDirs(root, manifest) {
  const declaredPaths = new Set(manifest.skills.map((entry) => entry.path));

  const errors = [];
  for (const child of readdirSync(root, { withFileTypes: true })) {
    if (child.name === "node_modules" || child.name.startsWith(".")) continue;

    // A symlink dirent is not a directory, so this scan used to skip one
    // silently even when it pointed at a skill. Bonsai's own loader follows it and
    // composes the skill on the other side, which is the same drift as rule 7's
    // but in the opposite direction: the marketplace ships a skill its own CI
    // never saw. Declared names are left to rule 7, which already reports the
    // symlink and owns every declared path.
    if (child.isSymbolicLink()) {
      if (!existsSync(join(root, child.name, "SKILL.md"))) continue;
      if (declaredPaths.has(child.name)) continue;
      errors.push(
        `marketplace.json: '${child.name}' is a symlink to a skill directory; a skill directory must be a real directory at the marketplace root`,
      );
      continue;
    }

    if (!child.isDirectory()) continue;
    if (!existsSync(join(root, child.name, "SKILL.md"))) continue;

    if (!declaredPaths.has(child.name)) {
      errors.push(
        `marketplace.json: skill directory '${child.name}' is not listed in marketplace.json`,
      );
    }
  }
  return errors;
}

// ---------------------------------------------------------------------------
// Plugin filesystem cross-checks and manifest reading: rules 19-24
// ---------------------------------------------------------------------------

/**
 * Rule 19, the plugin twin of rule 7: every declared plugin path must be a
 * real directory under `plugins/`. A symlink is named as its own error rather
 * than followed, for exactly the reasons rule 7 gives — a clone made with
 * `core.symlinks=false` materializes the link as a text file and the
 * directory simply is not there, and a link pointing outside the root lets CI
 * bless bytes the marketplace does not contain.
 */
function checkDeclaredPluginDirsExist(root, manifest) {
  const errors = [];
  for (const entry of manifest.plugins) {
    const dirAbs = resolvePluginDir(root, entry.path);
    if (isSymlink(dirAbs)) {
      errors.push(
        `marketplace.json: plugin '${entry.path}' is a symlink; a plugin directory must be a real directory under ${PLUGINS_DIR_NAME}/`,
      );
      continue;
    }
    if (!isRealDirectory(dirAbs)) {
      errors.push(
        `marketplace.json: plugin '${entry.path}' has no directory at ${pluginDisplayPath(entry.path)}`,
      );
    }
  }
  return errors;
}

/**
 * Rule 20, the plugin twin of rule 8: a plugin directory is defined
 * structurally — any directory directly under `plugins/` that contains a
 * `kay-plugin.json` — and every one of them needs a manifest entry. This is
 * the same claim the plugin channel itself makes on the other side: a plugin
 * repository source with `subdir: "plugins"` treats each immediate child
 * carrying a top-level `kay-plugin.json` as a plugin, so an undeclared one is
 * a plugin the marketplace ships and its own index never describes.
 *
 * A missing `plugins/` directory is not an error: a marketplace that carries
 * no plugins has nothing to scan, exactly as one that declares no skills is
 * still scanned at a root that simply holds none.
 */
function checkForUndeclaredPluginDirs(root, manifest) {
  const pluginsRoot = join(root, PLUGINS_DIR_NAME);
  if (isSymlink(pluginsRoot)) {
    return [
      `marketplace.json: '${PLUGINS_DIR_NAME}' is a symlink; it must be a real directory at the marketplace root`,
    ];
  }
  if (!isRealDirectory(pluginsRoot)) return [];

  const declaredPaths = new Set(manifest.plugins.map((entry) => entry.path));

  const errors = [];
  for (const child of readdirSync(pluginsRoot, { withFileTypes: true })) {
    if (child.name === "node_modules" || child.name.startsWith(".")) continue;

    // Same direction as rule 8's symlink branch: Bonsai's plugin scan follows a
    // symlink and finds the manifest on the other side, so skipping one here
    // would ship a plugin this CI never saw. Declared names belong to rule 19,
    // which already reports the symlink.
    if (child.isSymbolicLink()) {
      if (
        !existsSync(join(pluginsRoot, child.name, PLUGIN_MANIFEST_FILENAME))
      ) {
        continue;
      }
      if (declaredPaths.has(child.name)) continue;
      errors.push(
        `marketplace.json: '${pluginDisplayPath(child.name)}' is a symlink to a plugin directory; a plugin directory must be a real directory under ${PLUGINS_DIR_NAME}/`,
      );
      continue;
    }

    if (!child.isDirectory()) continue;
    if (!existsSync(join(pluginsRoot, child.name, PLUGIN_MANIFEST_FILENAME))) {
      continue;
    }

    if (!declaredPaths.has(child.name)) {
      errors.push(
        `marketplace.json: plugin directory '${pluginDisplayPath(child.name)}' is not listed in marketplace.json`,
      );
    }
  }
  return errors;
}

/** The declared `targets.kay` target names, sorted so the index is canonical rather than key-order dependent. */
function derivePluginTargets(manifest) {
  const targets = manifest.targets;
  if (typeof targets !== "object" || targets === null || Array.isArray(targets))
    return [];
  const kay = targets.kay;
  if (typeof kay !== "object" || kay === null || Array.isArray(kay)) return [];
  return Object.entries(kay)
    .filter(
      ([, value]) =>
        typeof value === "object" && value !== null && !Array.isArray(value),
    )
    .map(([name]) => name)
    .sort();
}

/** The declared `compatibility.sdk` range, or `""` when the plugin declares none. */
function derivePluginSdkRange(manifest) {
  const compatibility = manifest.compatibility;
  if (
    typeof compatibility !== "object" ||
    compatibility === null ||
    Array.isArray(compatibility)
  ) {
    return "";
  }
  return typeof compatibility.sdk === "string" ? compatibility.sdk : "";
}

/**
 * Rules 21-24 for one plugin: read its `kay-plugin.json`, hold its four
 * identity fields to the shape the index publishes, and bound everything the
 * author controls. Returns `{ errors }` or `{ manifest }`, never both.
 */
function readPluginManifest(root, entry) {
  const ctx = `${pluginDisplayPath(entry.path)}/${PLUGIN_MANIFEST_FILENAME}`;
  const manifestAbs = join(
    resolvePluginDir(root, entry.path),
    PLUGIN_MANIFEST_FILENAME,
  );
  if (!existsSync(manifestAbs)) {
    return { errors: [`${ctx} is missing`] };
  }

  let parsed;
  try {
    parsed = JSON.parse(readFileSync(manifestAbs, "utf8"));
  } catch (error) {
    return { errors: [`${ctx} is not valid JSON: ${error.message}`] };
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    return { errors: [`${ctx} must be a JSON object`] };
  }

  const errors = [];

  if (typeof parsed.id !== "string" || parsed.id.trim().length === 0) {
    errors.push(`${ctx}: 'id' must be a non-empty string`);
  } else if (!PLUGIN_ID_RE.test(parsed.id)) {
    errors.push(
      `${ctx}: 'id' must be dot-separated lowercase segments, for example 'com.example.my-plugin'`,
    );
  } else if (parsed.id.length > MAX_PLUGIN_ID_LENGTH) {
    errors.push(
      `${ctx}: 'id' exceeds ${MAX_PLUGIN_ID_LENGTH} characters (${parsed.id.length})`,
    );
  }

  if (typeof parsed.version !== "string" || !SEMVER_RE.test(parsed.version)) {
    errors.push(`${ctx}: 'version' must be semver, for example 1.2.3`);
  } else if (parsed.version.length > MAX_PLUGIN_VERSION_LENGTH) {
    errors.push(
      `${ctx}: 'version' exceeds ${MAX_PLUGIN_VERSION_LENGTH} characters (${parsed.version.length})`,
    );
  }

  for (const field of ["displayName", "description"]) {
    const value = parsed[field];
    if (typeof value !== "string" || value.trim().length === 0) {
      errors.push(`${ctx}: '${field}' must be a non-empty string`);
    } else if (value.length > MAX_PLUGIN_TEXT_LENGTH) {
      errors.push(
        `${ctx}: '${field}' exceeds ${MAX_PLUGIN_TEXT_LENGTH} characters (${value.length})`,
      );
    }
  }

  const sdk = derivePluginSdkRange(parsed);
  if (sdk.length > MAX_PLUGIN_SDK_RANGE_LENGTH) {
    errors.push(
      `${ctx}: 'compatibility.sdk' exceeds ${MAX_PLUGIN_SDK_RANGE_LENGTH} characters (${sdk.length})`,
    );
  }

  const targets = derivePluginTargets(parsed);
  if (targets.length > MAX_PLUGIN_TARGETS) {
    errors.push(
      `${ctx}: 'targets.kay' declares ${targets.length} targets; the limit is ${MAX_PLUGIN_TARGETS}`,
    );
  }
  for (const target of targets) {
    if (target.length > MAX_PLUGIN_TARGET_NAME_LENGTH) {
      errors.push(
        `${ctx}: target name '${target.slice(0, 32)}...' exceeds ${MAX_PLUGIN_TARGET_NAME_LENGTH} characters (${target.length})`,
      );
    }
  }

  if (errors.length > 0) return { errors };
  return {
    manifest: {
      id: parsed.id,
      displayName: parsed.displayName,
      description: parsed.description,
      version: parsed.version,
      sdk,
      targets,
    },
  };
}

/** Read and validate every declared plugin. Skips a path rule 19 already flagged; rule 23 catches a repeated id across the survivors. */
function readAndValidatePlugins(root, manifest) {
  const errors = [];
  const plugins = [];
  const seenIds = new Map();

  for (const entry of manifest.plugins) {
    // Same predicate rule 19 uses, so a path it already rejected is reported
    // once rather than again per manifest problem behind it.
    if (!isRealDirectory(resolvePluginDir(root, entry.path))) continue;

    const outcome = readPluginManifest(root, entry);
    if (outcome.errors !== undefined) {
      errors.push(...outcome.errors);
      continue;
    }

    // Rule 23. Two directories publishing one plugin id would give the
    // listing two rows Bonsai keys identically, and only one of them could ever
    // be the plugin a user enabled.
    const previous = seenIds.get(outcome.manifest.id);
    if (previous !== undefined) {
      errors.push(
        `marketplace.json: plugins '${previous}' and '${entry.path}' both declare the plugin id '${outcome.manifest.id}'`,
      );
      continue;
    }
    seenIds.set(outcome.manifest.id, entry.path);
    plugins.push({ entry, manifest: outcome.manifest });
  }

  return { errors, plugins };
}

// ---------------------------------------------------------------------------
// Artifact digest
//
// Every skill row and every plugin row in the index carries a content digest,
// "sha256:<64 lowercase hex chars>", computed purely from the artifact's own
// directory contents. Unlike `commit`, `creator`, and `contributors`, this
// digest has nothing to do with git history: it is reproducible from a bare
// clone with no history at all, which is exactly the property that lets Bonsai
// recompute it independently from the bytes it actually cloned and compare
// the result against a signed index entry (see marketplace.index.sig and
// tools/sign.mjs). That comparison is what promotes an artifact from an
// unverified source class to "verified marketplace": a validator that
// computed this differently than Bonsai does would make every artifact here
// unverifiable, silently.
//
// The algorithm, exactly (docs/skill-marketplace-format.md carries the
// normative version a second implementation must match byte for byte):
//   1. Walk the artifact's directory (the skill directory itself, or
//      plugins/<path> for a plugin) recursively.
//   2. Consider regular files only. ANY symlink anywhere in the tree is a
//      hard validation error naming the offending path, never a silent skip:
//      a symlink is content this digest cannot honestly cover.
//   3. Each file's path, relative to the artifact directory root, POSIX
//      separators, no leading './'.
//   4. One entry per file, the exact string: "<relpath>\n<sha256 hex of the
//      file's bytes>\n".
//   5. Sort entries by relpath, compared as UTF-8 BYTE sequences
//      (`Buffer.compare`, never `localeCompare` and never default
//      `Array.sort` string ordering: both diverge from a byte compare on
//      non-ASCII names).
//   6. Concatenate in sorted order; the digest is "sha256:" plus the sha256
//      of that concatenation, in lowercase hex.
//
// Unlike `commit`/`creator`/`contributors`, this digest IS derived purely
// from the file-derived content the staleness check (rule 15) already
// compares, so it is never excluded from that comparison: a content change
// with a stale committed digest must fail a check-only run exactly like a
// stale description would.
// ---------------------------------------------------------------------------

/**
 * Recursively walk `absDir`, collecting `{ relPath, absPath }` for every
 * regular file inside it. `relPath` uses POSIX separators and never a
 * leading './', regardless of platform. Returns `{ error: relPath }` naming
 * the first symlink found anywhere in the tree (a directory or a file, at
 * any depth), or `{ files }` once the whole tree is confirmed symlink-free.
 *
 * `readdirSync`'s own dirents are used to test for a symlink, the same way
 * `lstat` would: a dirent's type reflects the entry itself, never whatever it
 * points at, so nothing here ever needs to follow one to classify it.
 */
function walkArtifactTree(absDir, relDir = "") {
  const files = [];
  for (const child of readdirSync(absDir, { withFileTypes: true })) {
    const childAbs = join(absDir, child.name);
    const childRel = relDir === "" ? child.name : `${relDir}/${child.name}`;
    if (child.isSymbolicLink()) {
      return { error: childRel };
    }
    if (child.isDirectory()) {
      const nested = walkArtifactTree(childAbs, childRel);
      if (nested.error !== undefined) return nested;
      files.push(...nested.files);
      continue;
    }
    if (child.isFile()) {
      files.push({ relPath: childRel, absPath: childAbs });
    }
    // Anything else (a fifo, a socket, a device) is neither a symlink, a
    // directory, nor a regular file, and step 2 of the algorithm above
    // excludes it the same way it excludes nothing else: silently, since it
    // is not content a marketplace skill or plugin is ever expected to hold.
  }
  return { files };
}

/**
 * Compute one artifact's content digest per the algorithm above. Returns
 * `{ error: relPath }` when a symlink is found anywhere in the tree, or
 * `{ digest }`.
 */
function computeArtifactDigest(absDir) {
  const walked = walkArtifactTree(absDir);
  if (walked.error !== undefined) return { error: walked.error };

  const sorted = [...walked.files].sort((a, b) =>
    Buffer.compare(
      Buffer.from(a.relPath, "utf8"),
      Buffer.from(b.relPath, "utf8"),
    ),
  );

  const hash = createHash("sha256");
  for (const file of sorted) {
    const fileHash = createHash("sha256")
      .update(readFileSync(file.absPath))
      .digest("hex");
    hash.update(`${file.relPath}\n${fileHash}\n`, "utf8");
  }
  return { digest: `sha256:${hash.digest("hex")}` };
}

/**
 * Compute every surviving skill's and plugin's content digest up front, so a
 * symlink anywhere inside an artifact's own directory tree is reported as
 * the validation error it is, before any index is written — exactly like a
 * symlink standing where the artifact directory itself belongs (rules 7 and
 * 19), just one level deeper. Only entries `readAndValidateSkills` and
 * `readAndValidatePlugins` already accepted are considered: an entry rule 7,
 * 9, 19, or 21 already rejected is reported once, not again here.
 *
 * Returns `{ errors, skillDigests, pluginDigests }`. The two digest maps are
 * keyed by each entry's own `path` and contain only entries that resolved
 * cleanly.
 */
function computeArtifactDigests(root, skills, plugins) {
  const errors = [];
  const skillDigests = new Map();
  const pluginDigests = new Map();

  for (const { entry } of skills) {
    const outcome = computeArtifactDigest(resolveSkillDir(root, entry.path));
    if (outcome.error !== undefined) {
      errors.push(
        `marketplace.json: skill '${entry.path}' contains a symlink at '${entry.path}/${outcome.error}'; ` +
          "its digest cannot honestly cover a symlink",
      );
      continue;
    }
    skillDigests.set(entry.path, outcome.digest);
  }

  for (const { entry } of plugins) {
    const outcome = computeArtifactDigest(resolvePluginDir(root, entry.path));
    if (outcome.error !== undefined) {
      errors.push(
        `marketplace.json: plugin '${entry.path}' contains a symlink at '${pluginDisplayPath(entry.path)}/${outcome.error}'; ` +
          "its digest cannot honestly cover a symlink",
      );
      continue;
    }
    pluginDigests.set(entry.path, outcome.digest);
  }

  return { errors, skillDigests, pluginDigests };
}

// ---------------------------------------------------------------------------
// Minimal YAML-subset frontmatter parser
//
// Real SKILL.md frontmatter uses exactly this much of YAML: top-level
// `key: value` pairs, one level of nesting (how `metadata:` is written),
// plain scalars, "double" and 'single' quoted scalars, comments, and blank
// lines. Anything wider (block scalars, flow collections, anchors, aliases,
// sequences) is reported by name below, instead of silently mis-parsed: a
// silent mis-parse here would validate the wrong thing and say nothing.
//
// The rule this subset lives by: FAIL CLOSED on anything it cannot model the
// way Bonsai does. Bonsai parses the same frontmatter with a full YAML 1.2 parser,
// so a shape this subset would read differently, or would accept where Bonsai
// refuses the file, must be an error here and not a quiet pass. Otherwise a
// marketplace's CI blesses a skill Bonsai silently drops on the other end, which
// is the one failure this validator exists to prevent.
// ---------------------------------------------------------------------------

const NULL_SCALARS = new Set(["", "~", "null", "Null", "NULL"]);
const TRUE_SCALARS = new Set(["true", "True", "TRUE"]);
const FALSE_SCALARS = new Set(["false", "False", "FALSE"]);
// The numeric productions of YAML 1.2's core schema, which is what Bonsai's
// parser resolves a plain scalar against. Split by production because the
// schema is not uniform about signs: a leading '+' or '-' belongs to the
// decimal and infinity forms only. '-0x10' and '-.nan' are plain STRINGS to
// it, and stay strings here.
const NUMBER_SCALAR = /^[+-]?(\d+\.\d*|\.\d+|\d+)([eE][+-]?\d+)?$/;
const HEX_SCALAR = /^0x[0-9a-fA-F]+$/;
const OCTAL_SCALAR = /^0o[0-7]+$/;
const INFINITY_SCALAR = /^[+-]?\.(?:inf|Inf|INF)$/;
const NAN_SCALAR = /^\.(?:nan|NaN|NAN)$/;

/**
 * Characters that can never open a plain scalar: YAML reads each as the start
 * of some other node kind, and Bonsai's parser refuses the file outright for all
 * of them but `!`, where it instead resolves a TAG and hands back a different
 * value than the raw text. Both outcomes are worse than an error here.
 */
const LEADING_INDICATORS = new Map([
  ["!", "a tag ('!...')"],
  ["%", "a directive ('%...')"],
  ["@", "a reserved character ('@')"],
  ["`", "a reserved character ('`')"],
  [",", "a flow separator (',')"],
  ["]", "a flow-sequence end (']')"],
  ["}", "a flow-mapping end ('}')"],
]);

/**
 * Characters that open another node kind only when a space, a tab, or the end
 * of the line follows them. That conditional form is exactly why `-1.5` and
 * `10:30` are ordinary scalars while `- item` and `: item` are not.
 */
const CONDITIONAL_INDICATORS = new Map([
  ["-", "a sequence ('- ...')"],
  ["?", "an explicit key ('? ...')"],
  [":", "a value indicator (': ...')"],
]);

/** The index of the colon that separates a plain mapping key from its value, or -1. */
function findMappingColon(text) {
  for (let index = 0; index < text.length; index += 1) {
    if (text[index] !== ":") continue;
    const next = text[index + 1];
    if (next === undefined || next === " " || next === "\t") return index;
  }
  return -1;
}

/** A plain scalar's comment starts at a '#' preceded by whitespace, never inside a word. */
function stripPlainComment(text) {
  for (let index = 1; index < text.length; index += 1) {
    if (text[index] === "#" && /\s/u.test(text[index - 1]))
      return text.slice(0, index);
  }
  return text;
}

function parseDoubleQuoted(text, lineNumber) {
  const escapes = { n: "\n", t: "\t", r: "\r", '"': '"', "\\": "\\", 0: "\0" };
  let value = "";
  let index = 1;
  while (index < text.length) {
    const char = text[index];
    if (char === "\\") {
      const escaped = text[index + 1];
      // Anything outside the six escapes above is rejected rather than having
      // its backslash dropped. Bonsai's parser supports a wider set (\x41,
      // \u0041, \a and more) and errors on the rest, so dropping the backslash
      // would either invent a value Bonsai never reads ('a\x41b' as "ax41b"
      // instead of "aAb") or pass a file Bonsai refuses.
      if (escaped === undefined || !Object.hasOwn(escapes, escaped)) {
        return {
          error: `line ${lineNumber}: unsupported escape '\\${escaped ?? ""}' in a double-quoted scalar; only \\n, \\t, \\r, \\", \\\\ and \\0 are supported`,
        };
      }
      value += escapes[escaped];
      index += 2;
      continue;
    }
    if (char === '"') {
      const trailing = text.slice(index + 1).trim();
      if (trailing.length > 0 && !trailing.startsWith("#")) {
        return {
          error: `line ${lineNumber}: unexpected content after the closing quote`,
        };
      }
      return { value };
    }
    value += char;
    index += 1;
  }
  return { error: `line ${lineNumber}: unterminated double-quoted scalar` };
}

function parseSingleQuoted(text, lineNumber) {
  let value = "";
  let index = 1;
  while (index < text.length) {
    const char = text[index];
    if (char === "'") {
      if (text[index + 1] === "'") {
        value += "'";
        index += 2;
        continue;
      }
      const trailing = text.slice(index + 1).trim();
      if (trailing.length > 0 && !trailing.startsWith("#")) {
        return {
          error: `line ${lineNumber}: unexpected content after the closing quote`,
        };
      }
      return { value };
    }
    value += char;
    index += 1;
  }
  return { error: `line ${lineNumber}: unterminated single-quoted scalar` };
}

/** Parse one YAML scalar, or report the unsupported shape by name instead of guessing. */
function parseScalar(raw, lineNumber) {
  const trimmed = raw.trim();
  if (trimmed === "") return { value: null };

  const first = trimmed[0];
  // A plain scalar's value string reaches here only after the mandatory
  // whitespace that follows ':' (see findMappingColon), so a '#' as its very
  // first character was necessarily preceded by whitespace: the whole value
  // is a comment, i.e. no value at all (YAML null), not the literal text.
  if (first === "#") return { value: null };
  if (first === '"') return parseDoubleQuoted(trimmed, lineNumber);
  if (first === "'") return parseSingleQuoted(trimmed, lineNumber);
  if (first === "|" || first === ">") {
    return {
      error: `line ${lineNumber}: a block scalar ('${first}') is not supported in frontmatter`,
    };
  }
  if (first === "{") {
    return {
      error: `line ${lineNumber}: a flow mapping ('{...}') is not supported in frontmatter`,
    };
  }
  if (first === "[") {
    return {
      error: `line ${lineNumber}: a flow sequence ('[...]') is not supported in frontmatter`,
    };
  }
  if (first === "&") {
    return {
      error: `line ${lineNumber}: an anchor ('&') is not supported in frontmatter`,
    };
  }
  if (first === "*") {
    return {
      error: `line ${lineNumber}: an alias ('*') is not supported in frontmatter`,
    };
  }
  const leadingIndicator = LEADING_INDICATORS.get(first);
  if (leadingIndicator !== undefined) {
    return {
      error: `line ${lineNumber}: ${leadingIndicator} is not supported in frontmatter`,
    };
  }

  // Comment stripping happens before the two checks below so that both judge
  // the value a reader sees: 'abc # a: b' is the scalar 'abc', not a colon
  // problem.
  const value = stripPlainComment(trimmed).trim();

  const conditionalIndicator = CONDITIONAL_INDICATORS.get(value[0]);
  if (
    conditionalIndicator !== undefined &&
    (value.length === 1 || value[1] === " " || value[1] === "\t")
  ) {
    return {
      error: `line ${lineNumber}: ${conditionalIndicator} is not supported in frontmatter`,
    };
  }

  // A plain scalar ends at the first ':' that a space, a tab, or the end of
  // the line follows: to YAML that colon opens a nested mapping, which is
  // precisely what `findMappingColon` already recognizes one line up. Bonsai
  // refuses the whole file over it ('Nested mappings are not allowed in
  // compact mappings') and drops the skill, so 'description: foo: bar' must
  // never pass here as the string 'foo: bar'.
  if (findMappingColon(value) !== -1) {
    return {
      error: `line ${lineNumber}: a plain scalar cannot contain ':' followed by a space, a tab, or the end of the line; quote the value to keep the colon`,
    };
  }

  if (NULL_SCALARS.has(value)) return { value: null };
  if (TRUE_SCALARS.has(value)) return { value: true };
  if (FALSE_SCALARS.has(value)) return { value: false };
  // Every numeric production resolves to a NUMBER, exactly as Bonsai's parser
  // resolves it. That is the whole point: a `metadata.version: 0x10` is the
  // number 16 to Bonsai and fails its string requirement, so it has to fail the
  // same requirement here instead of being indexed as the string "0x10".
  if (NUMBER_SCALAR.test(value)) return { value: Number(value) };
  // Number() reads both '0x'- and '0o'-prefixed literals natively, and the
  // regexes above already fixed the exact accepted shape.
  if (HEX_SCALAR.test(value) || OCTAL_SCALAR.test(value)) {
    return { value: Number(value) };
  }
  if (INFINITY_SCALAR.test(value)) {
    return { value: value.startsWith("-") ? -Infinity : Infinity };
  }
  if (NAN_SCALAR.test(value)) return { value: Number.NaN };
  return { value };
}

/** Set `map[key] = value`, or `{ error }` naming the key when it is already set: a repeated key is rejected, never silently last-value-wins. */
function setUniqueKey(map, key, value, lineNumber) {
  if (Object.hasOwn(map, key)) {
    return { error: `line ${lineNumber}: duplicate frontmatter key '${key}'` };
  }
  map[key] = value;
  return null;
}

/** Parse the minimal YAML subset into a plain object, or `{ error }` naming the first problem. */
function parseMinimalYaml(text) {
  const entries = [];
  const lines = text.split(/\r?\n/);
  for (let offset = 0; offset < lines.length; offset += 1) {
    const rawLine = lines[offset];
    if (/^\s*$/u.test(rawLine)) continue;
    if (/^\s*#/u.test(rawLine)) continue;
    const indent = rawLine.length - rawLine.trimStart().length;
    // A tab in the indentation is a hard YAML error ('Tabs are not allowed as
    // indentation'), so Bonsai refuses the whole file. Counting it as one indent
    // column instead, as this parser otherwise would, passes a file Bonsai never
    // loads. Blank and comment lines are already skipped above, matching YAML:
    // a tab is only indentation when a node follows it.
    if (rawLine.slice(0, indent).includes("\t")) {
      return {
        error: `line ${offset + 1}: tabs are not allowed as indentation; use spaces`,
      };
    }
    entries.push({ indent, text: rawLine.trim(), lineNumber: offset + 1 });
  }

  // A sequence item, top-level or nested under a mapping key, is rejected by
  // name rather than mis-parsed: without this check the leading '- ' would
  // land inside findMappingColon's key slice, e.g. 'metadata:' followed by
  // '- version: 1.0' silently keys the map as "- version" instead of
  // "version". Checked over every entry up front, so it catches a sequence
  // at any indentation level, not only at the root.
  for (const entry of entries) {
    if (entry.text === "-" || entry.text.startsWith("- ")) {
      return {
        error: `line ${entry.lineNumber}: a sequence ('- ...') is not supported in frontmatter`,
      };
    }
  }

  const root = {};
  let index = 0;
  while (index < entries.length) {
    const entry = entries[index];
    if (entry.indent !== 0) {
      return { error: `line ${entry.lineNumber}: unexpected indentation` };
    }

    const colon = findMappingColon(entry.text);
    if (colon === -1) {
      return {
        error: `line ${entry.lineNumber}: could not parse "${entry.text}" as 'key: value'`,
      };
    }
    const key = entry.text.slice(0, colon).trim();
    const restRaw = entry.text.slice(colon + 1).trim();
    const next = entries[index + 1];

    if (restRaw !== "") {
      // An inline value. Checked before looking at what follows, so a real block
      // scalar ('description: |' with indented lines under it) is reported by
      // name rather than mistaken for an attempted nested map.
      const parsed = parseScalar(restRaw, entry.lineNumber);
      if (parsed.error) return parsed;
      if (next && next.indent > 0) {
        return {
          error: `line ${next.lineNumber}: unexpected indentation after '${key}: ...'`,
        };
      }
      const dupInline = setUniqueKey(root, key, parsed.value, entry.lineNumber);
      if (dupInline) return dupInline;
      index += 1;
      continue;
    }

    if (!next || next.indent === 0) {
      // An empty value with nothing indented under it: a YAML null.
      const dupNull = setUniqueKey(root, key, null, entry.lineNumber);
      if (dupNull) return dupNull;
      index += 1;
      continue;
    }

    // An empty value with indented lines under it: one level of nesting.
    const childIndent = next.indent;
    const children = [];
    let cursor = index + 1;
    while (cursor < entries.length && entries[cursor].indent > 0) {
      if (entries[cursor].indent !== childIndent) {
        return {
          error: `line ${entries[cursor].lineNumber}: only one level of nesting is supported in frontmatter`,
        };
      }
      children.push(entries[cursor]);
      cursor += 1;
    }

    const childMap = {};
    for (const child of children) {
      const childColon = findMappingColon(child.text);
      if (childColon === -1) {
        return {
          error: `line ${child.lineNumber}: could not parse "${child.text}" as 'key: value'`,
        };
      }
      const childKey = child.text.slice(0, childColon).trim();
      const childRest = child.text.slice(childColon + 1).trim();
      if (childRest === "") {
        const dupChildNull = setUniqueKey(
          childMap,
          childKey,
          null,
          child.lineNumber,
        );
        if (dupChildNull) return dupChildNull;
        continue;
      }
      const parsedChild = parseScalar(childRest, child.lineNumber);
      if (parsedChild.error) return parsedChild;
      const dupChild = setUniqueKey(
        childMap,
        childKey,
        parsedChild.value,
        child.lineNumber,
      );
      if (dupChild) return dupChild;
    }

    const dupRoot = setUniqueKey(root, key, childMap, entry.lineNumber);
    if (dupRoot) return dupRoot;
    index = cursor;
  }

  return { value: root };
}

/** Extract and parse a SKILL.md's frontmatter block. `ctx` is the SKILL.md path for messages. */
function parseFrontmatterBlock(fileText, ctx) {
  // A leading UTF-8 BOM is invisible in an editor but is a real first
  // character to the `startsWith("---")` test Bonsai's loader opens with: a
  // BOM-saved SKILL.md has no frontmatter at all as far as Bonsai is concerned,
  // so the whole file becomes body, the skill has no description, and Bonsai
  // drops it. Stripping the BOM here would bless a file that never loads, so
  // it is named as the error it is, with the one-line fix.
  if (fileText.startsWith("\uFEFF")) {
    return {
      error: `${ctx}: file begins with a UTF-8 byte-order mark; save SKILL.md without a BOM`,
    };
  }
  const text = fileText;
  // The closing delimiter is matched as '^---' under /m rather than the
  // literal '\r?\n---' this replaces, so a truly empty block ('---\n---',
  // with nothing between the two marker lines, i.e. only one newline
  // separating them) still matches: a fixed '\r?\n---' after the capture
  // group would demand a second newline that a zero-line body can't supply.
  const match = /^---\r?\n([\s\S]*?)^---/mu.exec(text);
  if (!match) {
    return {
      error: `${ctx}: missing or unparsable frontmatter (no leading '---' block)`,
    };
  }
  const parsed = parseMinimalYaml(match[1]);
  if (parsed.error) return { error: `${ctx}: ${parsed.error}` };
  return { value: parsed.value };
}

