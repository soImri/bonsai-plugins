#!/usr/bin/env node
// Build the single-file UI entry: ui/entry.tsx (+ ui/kit.tsx + connectors/*/ui.tsx) → kay-ui.tsx
//
// Bonsai bundles a plugin's UI entry from its TEXT in a virtual folder, so the entry cannot import
// sibling files (the agent entry can). This script bundles the UI sources with esbuild into one
// file, keeping React and the Bonsai SDK as imports for Bonsai to resolve, and JSX intact.
// Run it before every commit that touches ui/ or a connector's ui.tsx; commit the output.
import { spawnSync } from "node:child_process";
import { access, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, "kay-ui.tsx");
const candidates = [process.env.ESBUILD, join(root, "node_modules", ".bin", "esbuild"), join(process.env.HOME ?? "", "bonsai-ui-demo", "node_modules", ".bin", "esbuild")].filter(Boolean);
let esbuild;
for (const c of candidates) { try { await access(c); esbuild = [c]; break; } catch { /* next */ } }
esbuild ??= ["npx", "-y", "esbuild@0.25"];

const args = ["ui/entry.tsx", "--bundle", "--format=esm", "--jsx=preserve", "--platform=browser", "--external:react", "--external:react-dom", "--external:react/*", "--external:@bonsai/*", "--log-level=warning", `--outfile=${out}`];
const r = spawnSync(esbuild[0], [...esbuild.slice(1), ...args], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
if (r.status !== 0) { console.error(r.stderr || r.stdout); process.exit(r.status ?? 1); }
const built = await readFile(out, "utf8");
await writeFile(out, `// GENERATED by tools/build-ui.mjs from ui/entry.tsx, ui/kit.tsx and each connector's ui.tsx. Do not edit; edit the sources and rebuild.\n${built}`);
console.log(`built kay-ui.tsx (${built.length} chars) with ${esbuild.join(" ")}`);
